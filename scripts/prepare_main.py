#!/usr/bin/env python3
"""One-time preparation: build the fully-offline LOCAL-LAB-AI deployment.

This step USES THE INTERNET. It never runs automatically - the student
explicitly runs `prepare` once. Afterwards, `start` needs no network access
at all.

Prerequisite: Python 3.10+ must already be installed on the machine to run
this script (and, since `start` reuses the isolated virtualenv this script
creates, to run `start` too). Everything else - the inference engine, the
model weights, all pip dependencies including OCR - is fetched here and
stored under the project so `start` is 100% offline afterward.

This file is intentionally stdlib-only up to the point where the venv
exists, so it can run before anything has been pip-installed.
"""

from __future__ import annotations

import json
import os
import platform
import subprocess
import sys
import venv
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import is_windows, log, project_root, sha256_of_file  # noqa: E402


def _venv_python(venv_dir: Path) -> Path:
    return venv_dir / ("Scripts/python.exe" if is_windows() else "bin/python3")


def ensure_venv(root: Path) -> Path:
    venv_dir = root / "runtime" / "venv"
    py = _venv_python(venv_dir)
    if py.exists():
        log(f"Virtual environment already exists at {venv_dir}")
        return py

    log(f"Creating virtual environment at {venv_dir} ...")
    venv.EnvBuilder(with_pip=True, upgrade_deps=True).create(venv_dir)
    if not py.exists():
        raise RuntimeError(f"venv creation appeared to succeed but {py} is missing")
    return py


def install_requirements(root: Path, venv_python: Path) -> None:
    log("Installing Python dependencies (this needs internet access to pypi.org)...")
    subprocess.run(
        [str(venv_python), "-m", "pip", "install", "--upgrade", "pip"],
        check=True, cwd=str(root),
    )
    subprocess.run(
        [str(venv_python), "-m", "pip", "install", "-r", "requirements.txt"],
        check=True, cwd=str(root),
    )


def run_step(venv_python: Path, root: Path, script: str) -> dict:
    result = subprocess.run(
        [str(venv_python), script],
        cwd=str(root),
        capture_output=True,
        text=True,
    )
    if result.stdout:
        print(result.stdout, end="")
    if result.returncode != 0:
        log(f"WARNING: {script} did not complete successfully:")
        print(result.stderr, file=sys.stderr)
        return {"status": "failed", "stderr": result.stderr.strip()}
    try:
        return json.loads(result.stdout.strip().splitlines()[-1]) if result.stdout.strip() else {"status": "unknown"}
    except (json.JSONDecodeError, IndexError):
        return {"status": "unknown", "raw_output": result.stdout}


def detect_hardware_and_tune(venv_python: Path, root: Path) -> dict:
    probe = (
        "import json, sys; sys.path.insert(0, 'backend'); "
        "from app.core.hardware import detect_hardware, recommend_llm_profile; "
        "hw = detect_hardware(); profile = recommend_llm_profile(hw); "
        "print(json.dumps({'hardware': hw.as_dict(), 'profile': profile}))"
    )
    result = subprocess.run(
        [str(venv_python), "-c", probe], cwd=str(root), capture_output=True, text=True,
    )
    if result.returncode != 0:
        log("WARNING: hardware detection failed; using conservative built-in defaults.")
        print(result.stderr, file=sys.stderr)
        return {}
    return json.loads(result.stdout.strip())


def write_local_config(root: Path, profile: dict) -> None:
    if not profile:
        return
    local_config_path = root / "config" / "local.yaml"
    lines = [
        "# Auto-generated by `prepare` based on detected hardware.",
        "# Delete this file (or edit it) to fall back to / override config/default.yaml.",
        "llm:",
        f"  context_size: {profile['context_size']}",
        f"  threads: {profile['threads']}",
        f"  batch_size: {profile['batch_size']}",
        f"  kv_cache_type: \"{profile['kv_cache_type']}\"",
        "",
    ]
    local_config_path.write_text("\n".join(lines), encoding="utf-8")
    log(f"Wrote hardware-tuned config to {local_config_path} (tier: {profile.get('tier')})")


def check_ocr(venv_python: Path, root: Path) -> bool:
    log("Verifying local OCR (RapidOCR) is importable ...")
    result = subprocess.run(
        [str(venv_python), "-c", "from rapidocr_onnxruntime import RapidOCR; RapidOCR(); print('OK')"],
        cwd=str(root), capture_output=True, text=True,
    )
    ok = result.returncode == 0 and "OK" in result.stdout
    log("OCR OK." if ok else f"OCR check failed:\n{result.stderr}")
    return ok


def build_manifest(root: Path, engine_result: dict, model_result: dict, ocr_ok: bool) -> dict:
    manifest = {
        "app_version": "1.0.0",
        "prepared_at": __import__("time").time(),
        "platform": platform.system(),
        "arch": platform.machine(),
        "engine": engine_result,
        "model": model_result,
        "ocr_available": ocr_ok,
    }

    bin_name = "llama-server.exe" if is_windows() else "llama-server"
    engine_binary = root / "runtime" / "bin" / bin_name
    if engine_binary.exists():
        manifest["engine"]["installed_sha256"] = sha256_of_file(engine_binary)

    manifest_path = root / "manifest.json"
    manifest_path.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    log(f"Wrote {manifest_path}")
    return manifest


def main() -> int:
    root = project_root()
    os.chdir(root)
    log(f"Preparing LOCAL-LAB-AI at {root}")
    log(f"Detected platform: {platform.system()} {platform.machine()}")

    venv_python = ensure_venv(root)
    install_requirements(root, venv_python)

    hw_info = detect_hardware_and_tune(venv_python, root)
    if hw_info:
        write_local_config(root, hw_info.get("profile", {}))
        hw = hw_info.get("hardware", {})
        log(
            f"Hardware: {hw.get('logical_cores')} logical cores, "
            f"{hw.get('total_ram_gb')} GB RAM, GPU detected: {hw.get('gpu_detected')}"
        )

    log("Acquiring local inference engine (llama.cpp) ...")
    engine_result = run_step(venv_python, root, "engine/acquire_engine.py")

    log("Acquiring local model weights ...")
    model_result = run_step(venv_python, root, "engine/acquire_model.py")
    if model_result.get("status") == "failed":
        log(
            "MODEL DOWNLOAD DID NOT COMPLETE. This usually means this machine's "
            "network cannot reach huggingface.co. `start` will not be able to run "
            "chat completions until a model file exists at models/llm/. See "
            "engine/acquire_model.py's error output above for a manual download link."
        )

    ocr_ok = check_ocr(venv_python, root)

    build_manifest(root, engine_result, model_result, ocr_ok)

    log("=" * 60)
    log("PREPARE SUMMARY")
    log(f"  Engine : {engine_result.get('status')}")
    log(f"  Model  : {model_result.get('status')}")
    log(f"  OCR    : {'ok' if ocr_ok else 'FAILED'}")
    log("=" * 60)

    engine_ok = engine_result.get("status") in ("installed", "already-installed")
    model_ok = model_result.get("status") in ("installed", "already-installed", "already-installed-unverified")

    if engine_ok and model_ok and ocr_ok:
        log("Preparation complete. You can now run `start` fully offline.")
        return 0

    log("Preparation finished with warnings - see above. Run `offline-check` for a full report.")
    return 1


if __name__ == "__main__":
    sys.exit(main())
